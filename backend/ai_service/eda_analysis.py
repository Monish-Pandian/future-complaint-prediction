import pandas as pd
import numpy as np

df = pd.read_csv('data/raw/chicago_311_sample.csv')

# Convert dates
df['created_date'] = pd.to_datetime(df['created_date'], errors='coerce')
df['closed_date'] = pd.to_datetime(df['closed_date'], errors='coerce')

print('=' * 60)
print('1. DATASET OVERVIEW')
print('=' * 60)
print(f'Number of rows: {len(df)}')
print(f'Number of columns: {len(df.columns)}')
print(f'Column names: {list(df.columns)}')
print()
print('Data types:')
print(df.dtypes)
print()

print('=' * 60)
print('2. DATE ANALYSIS')
print('=' * 60)
print(f'Minimum created_date: {df["created_date"].min()}')
print(f'Maximum created_date: {df["created_date"].max()}')
print(f'Number of unique dates: {df["created_date"].dt.date.nunique()}')
print()
print('Records per date (top 20):')
date_counts = df.groupby(df['created_date'].dt.date).size().sort_values(ascending=False)
print(date_counts.head(20))
print()
print(f'Date range: {(df["created_date"].max() - df["created_date"].min()).days} days')
print()

print('=' * 60)
print('3. COMPLAINT TYPE ANALYSIS')
print('=' * 60)
print(f'Number of unique sr_type values: {df["sr_type"].nunique()}')
print()
print('Top 30 complaint types by frequency:')
type_counts = df['sr_type'].value_counts().head(30)
type_pct = (type_counts / len(df) * 100).round(2)
for idx, (ctype, count) in enumerate(type_counts.items(), 1):
    print(f'{idx:2d}. {ctype}: {count} ({type_pct[ctype]}%)')
print()

print('=' * 60)
print('4. DEPARTMENT ANALYSIS')
print('=' * 60)
print(f'Number of unique owner_department values: {df["owner_department"].nunique()}')
print()
print('Top 20 departments:')
dept_counts = df['owner_department'].value_counts().head(20)
dept_pct = (dept_counts / len(df) * 100).round(2)
for idx, (dept, count) in enumerate(dept_counts.items(), 1):
    print(f'{idx:2d}. {dept}: {count} ({dept_pct[dept]}%)')
print()

print('=' * 60)
print('5. STATUS ANALYSIS')
print('=' * 60)
status_counts = df['status'].value_counts()
status_pct = (status_counts / len(df) * 100).round(2)
for status, count in status_counts.items():
    print(f'{status}: {count} ({status_pct[status]}%)')
print()

print('=' * 60)
print('6. GEOGRAPHIC ANALYSIS')
print('=' * 60)
geo_fields = ['latitude', 'longitude', 'ward', 'community_area', 'zip_code']
for field in geo_fields:
    non_null = df[field].notna().sum()
    missing = df[field].isna().sum()
    missing_pct = (missing / len(df) * 100).round(2)
    unique = df[field].nunique()
    print(f'{field}:')
    print(f'  Non-null: {non_null}')
    print(f'  Missing: {missing} ({missing_pct}%)')
    print(f'  Unique values: {unique}')
    print()

print('=' * 60)
print('7. COORDINATE VALIDATION')
print('=' * 60)
both_coords = df['latitude'].notna() & df['longitude'].notna()
missing_either = (~df['latitude'].notna()) | (~df['longitude'].notna())
print(f'Records with both latitude AND longitude: {both_coords.sum()}')
print(f'Records missing either coordinate: {missing_either.sum()}')
print()
print('Latitude range:', df['latitude'].min(), 'to', df['latitude'].max())
print('Longitude range:', df['longitude'].min(), 'to', df['longitude'].max())
print()
# Chicago bounds: lat ~41.6 to 42.1, lon ~-87.9 to -87.5
valid_lat = df['latitude'].between(41.6, 42.1)
valid_lon = df['longitude'].between(-87.9, -87.5)
print(f'Records with valid Chicago latitude (41.6-42.1): {valid_lat.sum()}')
print(f'Records with valid Chicago longitude (-87.9 to -87.5): {valid_lon.sum()}')
print(f'Records with both valid: {(valid_lat & valid_lon).sum()}')
print()

print('=' * 60)
print('8. DUPLICATE ANALYSIS')
print('=' * 60)
dup_sr = df['sr_number'].duplicated().sum()
total_dup_rows = df.duplicated().sum()
unique_sr = df['sr_number'].nunique()
print(f'Duplicate sr_number values: {dup_sr}')
print(f'Total duplicate rows (all columns): {total_dup_rows}')
print(f'Unique sr_number values: {unique_sr}')
print()

print('=' * 60)
print('9. CLOSED-DATE ANALYSIS')
print('=' * 60)
has_closed = df['closed_date'].notna().sum()
no_closed = df['closed_date'].isna().sum()
print(f'Records with closed_date: {has_closed} ({has_closed/len(df)*100:.2f}%)')
print(f'Records without closed_date: {no_closed} ({no_closed/len(df)*100:.2f}%)')
print()

# Resolution time
resolved = df.dropna(subset=['created_date', 'closed_date']).copy()
resolved['resolution_hours'] = (resolved['closed_date'] - resolved['created_date']).dt.total_seconds() / 3600
print(f'Records with both dates: {len(resolved)}')
if len(resolved) > 0:
    print(f'Resolution time (hours) - Median: {resolved["resolution_hours"].median():.2f}')
    print(f'Resolution time (hours) - Mean: {resolved["resolution_hours"].mean():.2f}')
    print(f'Resolution time (hours) - Min: {resolved["resolution_hours"].min():.2f}')
    print(f'Resolution time (hours) - Max: {resolved["resolution_hours"].max():.2f}')
print()

