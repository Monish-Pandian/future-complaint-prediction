import React from 'react';
import { useNavigate } from 'react-router-dom';
import Card from '../common/Card';

export default function OperationsPipeline({ pipelineData = {} }) {
  const navigate = useNavigate();

  const stages = [
    {
      id: 'predictions',
      step: '01',
      title: 'Predictions',
      count: pipelineData.totalPredictions ?? 770,
      description: 'Future complaint risk generated by xgb-test-v1',
      path: '/predictions',
      status: 'Active Batch',
      accentColor: '#3b82f6',
    },
    {
      id: 'selection',
      step: '02',
      title: 'Priority Selection',
      count: pipelineData.selectedCandidates ?? (pipelineData.assignedCount ? pipelineData.assignedCount : 39),
      description: 'Operational budget with 90/10 exploitation-exploration policy',
      path: '/verification/candidates',
      status: '90:10 Policy',
      accentColor: '#06b6d4',
    },
    {
      id: 'assignment',
      step: '03',
      title: 'Officer Assignment',
      count: pipelineData.assignedCount ?? 39,
      description: 'Multi-factor match (0.4 Risk + 0.3 Distance + 0.3 Workload)',
      path: '/assignments',
      status: 'Dispatched',
      accentColor: '#8b5cf6',
    },
    {
      id: 'verification',
      step: '04',
      title: 'Field Verification',
      count: pipelineData.verifiedCount ?? 16,
      description: 'Field officer ground-truth inspection and evidence logs',
      path: '/verification',
      status: 'Ground Truth',
      accentColor: '#f59e0b',
    },
    {
      id: 'evaluation',
      step: '05',
      title: 'Evaluation',
      count: pipelineData.evaluatedCount ?? 19,
      description: 'Prediction-level outcome assessment & closed-loop retraining buffer',
      path: '/evaluations',
      status: 'Closed Loop',
      accentColor: '#10b981',
    },
  ];

  return (
    <Card
      title="Prediction-to-Action Pipeline"
      subtitle="End-to-end closed-loop predictive civic governance workflow"
      className="pipeline-card"
    >
      <div className="pipeline-flow-container">
        {stages.map((stage, idx) => (
          <div key={stage.id} className="pipeline-stage-wrapper">
            <div
              className="pipeline-stage-card"
              onClick={() => navigate(stage.path)}
              role="button"
              tabIndex={0}
              onKeyDown={(e) => e.key === 'Enter' && navigate(stage.path)}
              aria-label={`${stage.title}: ${stage.count} items. Click to open ${stage.title}`}
            >
              <div className="pipeline-stage-top">
                <span className="pipeline-step-badge font-mono">{stage.step}</span>
                <span
                  className="pipeline-status-chip font-mono"
                  style={{
                    color: stage.accentColor,
                    borderColor: `${stage.accentColor}40`,
                    background: `${stage.accentColor}15`,
                  }}
                >
                  {stage.status}
                </span>
              </div>

              <div className="pipeline-stage-title">{stage.title}</div>

              <div className="pipeline-stage-count font-mono" style={{ color: stage.accentColor }}>
                {typeof stage.count === 'number' ? stage.count.toLocaleString() : stage.count}
              </div>

              <div className="pipeline-stage-desc">{stage.description}</div>

              <div className="pipeline-stage-link">
                <span>View Stage</span>
                <svg width="12" height="12" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                  <polyline points="9 18 15 12 9 6" />
                </svg>
              </div>
            </div>

            {idx < stages.length - 1 && (
              <div className="pipeline-arrow" aria-hidden="true">
                <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                  <polyline points="9 18 15 12 9 6" />
                </svg>
              </div>
            )}
          </div>
        ))}
      </div>
    </Card>
  );
}
